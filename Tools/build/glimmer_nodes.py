"""Build Glimmer's herbs, veins and chests, and where the herbs and veins grow, from Wowhead Forever.

Wowhead's herb, mining node and chest lists (wowhead.com/forever/objects/herbs, /mineral-veins,
/chests) give every object's ID and the gathering skill it needs. World chests such as Battered
Chest are not in the chest list but in the container list, so a container whose name is a chest's
is a chest too. Each herb and vein's own page has where it grows, as map percentages by world map
ID (g_mapperData; a floor with no world map is left out); those spots are kept in Tools/data/glimmer_spots.json, delete it to ask again.

Writes NaowhForever_QoL/Glimmer/Data/Nodes.lua and NaowhForever_GlimmerData/Data/Spots.lua.

Usage: python Tools/build/glimmer_nodes.py
"""
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import paths  # noqa: E402
from wowhead import WOWHEAD, fetch  # noqa: E402
from journal import ROOT, header, write  # noqa: E402

OUT = ROOT / "NaowhForever_QoL" / "Glimmer" / "Data" / "Nodes.lua"
SPOTS_OUT = ROOT / "NaowhForever_GlimmerData" / "Data" / "Spots.lua"
CACHE = paths.DATA / "glimmer_spots.json"
LISTS = (("herb", "herbs"), ("ore", "mineral-veins"), ("chest", "chests"))
CHEST_NAME = re.compile(r"\b(Chest|Strongbox|Footlocker|Coffer|Lockbox|Trunk)\b")
TENTHS = 10
PER_LINE = 30


def rows(page):
    """The rows of a page's object listview."""
    start = page.index('"data":[') + len('"data":')
    return json.JSONDecoder().raw_decode(page[start:])[0]


def spots(object_id):
    """{ map ID: [[x, y], ...] } from the object's page."""
    page = fetch(f"{WOWHEAD}/object={object_id}")
    m = re.search(r"g_mapperData = (\{.*?\});", page)
    found = {}
    for floors in (json.loads(m.group(1)) if m else {}).values():
        for floor in floors:
            if "uiMapId" in floor:
                found.setdefault(str(floor["uiMapId"]), []).extend(floor["coords"])
    return found


def write_nodes(nodes):
    lines = header(OUT.name, "every herb, vein and chest on Forever by object ID, generated by "
                   "Tools/build/glimmer_nodes.py")
    lines.append("ns.Glimmer.NODES = {")
    for object_id in sorted(nodes):
        kind, skill, name = nodes[object_id]
        lines.append(f'    [{object_id}] = {{ "{kind}", {skill}, {json.dumps(name)} }},')
    lines.append("}")
    write(OUT, lines)
    counts = {k: sum(1 for v in nodes.values() if v[0] == k) for k, _ in LISTS}
    print(f"wrote {OUT.relative_to(ROOT)}: {counts}")


def write_spots(nodes):
    cache = json.loads(CACHE.read_text(encoding="utf-8")) if CACHE.exists() else {}
    for object_id, (kind, _, _) in sorted(nodes.items()):
        if kind != "chest" and str(object_id) not in cache:
            print(f"object {object_id}")
            cache[str(object_id)] = spots(object_id)
            CACHE.write_text(json.dumps(cache, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    by_map = {}
    for object_id in sorted(cache, key=int):
        for map_id, coords in cache[object_id].items():
            row = by_map.setdefault(int(map_id), [])
            seen = set()
            for x, y in coords:
                spot = (round(x * TENTHS), round(y * TENTHS))
                if spot not in seen:
                    seen.add(spot)
                    row += [int(object_id), spot[0], spot[1]]
    lines = header(SPOTS_OUT.name, "where every herb and vein grows, by world map, generated by "
                   "Tools/build/glimmer_nodes.py")
    lines.append("ns.GlimmerSpots = {")
    for map_id in sorted(by_map):
        values = [str(v) for v in by_map[map_id]]
        lines.append(f"    [{map_id}] = {{")
        for i in range(0, len(values), PER_LINE):
            lines.append("        " + ", ".join(values[i:i + PER_LINE]) + ",")
        lines.append("    },")
    lines.append("}")
    write(SPOTS_OUT, lines)
    total = sum(len(r) // 3 for r in by_map.values())
    print(f"wrote {SPOTS_OUT.relative_to(ROOT)}: {total} spots on {len(by_map)} maps")


def main():
    nodes = {}
    for kind, slug in LISTS:
        for row in rows(fetch(f"{WOWHEAD}/objects/{slug}")):
            nodes[row["id"]] = (kind, row.get("skill") or 0, row["name"])
    for row in rows(fetch(f"{WOWHEAD}/objects/containers")):
        if row["id"] not in nodes and CHEST_NAME.search(row["name"]):
            nodes[row["id"]] = ("chest", 0, row["name"])
    write_nodes(nodes)
    write_spots(nodes)


if __name__ == "__main__":
    main()
